"""Real TLS/socket/file integration for restricted remote publisher quarantine.

Certificate + private key are generated by actual local OpenSSL in a POSIX
temporary owner-only directory; never shipped or present in git.
"""
import hashlib
import json
import os
from pathlib import Path
import secrets
import shutil
import socket
import ssl
import subprocess
import sys
import tempfile
import threading
import unittest
from urllib.request import Request, urlopen
from urllib.error import HTTPError, URLError

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import private_publisher_inbox as inbox
import publisher_intake_service as gateway
import remote_publisher_tls_service as remote
import remote_publisher_submit as publisher
import publisher_token_lifecycle as token_admin


@unittest.skipUnless(os.name == "posix" and shutil.which("openssl"),
                     "actual POSIX private TLS and official OpenSSL required")
class RealRemotePublisherTLSIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory(prefix="hamapp-remote-tls-real-")
        self.addCleanup(self.tmp.cleanup)
        self.work = Path(self.tmp.name)
        self.root = inbox.init_root(self.work / "quarantine")
        self.incoming = inbox.init_root(self.work / "upload-temp")
        self.credentials = self.work / "publisher-credentials.json"
        self.token = gateway.provision(self.credentials, "publisher-first")
        self.token_file = self.work / "first-secret-token.txt"
        self.token_file.write_text(self.token + "\n", encoding="ascii")
        self.token_file.chmod(0o600)
        self.second_token = secrets.token_urlsafe(48)
        reg = json.loads(self.credentials.read_text("utf-8"))
        reg["publishers"].append({
            "source_repo": "publisher-second",
            "token_sha256": hashlib.sha256(self.second_token.encode("ascii")).hexdigest()
        })
        self.credentials.write_text(json.dumps(reg), encoding="utf-8")
        self.credentials.chmod(0o600)
        self.cert = self.work / "server.pem"
        self.key = self.work / "server.key"
        command = [
            "openssl", "req", "-new", "-x509", "-newkey", "rsa:2048",
            "-noenc", "-days", "1", "-subj", "/CN=localhost",
            "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1",
            "-keyout", str(self.key), "-out", str(self.cert)
        ]
        result = subprocess.run(command, capture_output=True, text=True,
                                check=False, timeout=25)
        if result.returncode:
            raise AssertionError("actual OpenSSL test certificate generation failed")
        self.key.chmod(0o600)
        self.pin = hashlib.sha256(
            ssl.PEM_cert_to_DER_cert(self.cert.read_text("ascii"))).hexdigest()
        self.candidate = self.work / "candidate.json"
        self.body = b"REAL-TLS-TRANSPORT-NONEXECUTABLE-TEST-FIXTURE"
        self.binary = self.work / "candidate.exe"
        self.binary.write_bytes(self.body)
        self.manifest = {
            "release": {
                "app_id": "sample",
                "platform": "windows",
                "version": "1.2.3",
                "asset_url": ("https://github.com/rezamahrm100-ops/publisher-first/"
                              "releases/download/v1.2.3/candidate.exe"),
                "sha256": hashlib.sha256(self.body).hexdigest(),
                "size_bytes": len(self.body)
            },
            "source_repo": "publisher-first",
            "source_sha": "b" * 40,
            "package_id": None,
            "version_code": None
        }
        self.candidate.write_text(json.dumps(self.manifest), encoding="utf-8")
        self.server = remote.TLSQuarantineServer(
            self.root, self.incoming, self.credentials, self.cert, self.key)
        self.thread = threading.Thread(target=self.server.serve_forever,
                                       kwargs={"poll_interval": 0.1}, daemon=True)
        self.thread.start()
        self.addCleanup(self.stop_server)
        self.origin = "https://localhost:%d" % self.server.server_port

    def stop_server(self):
        self.server.shutdown()
        self.server.server_close()
        self.thread.join(timeout=6)

    def send(self, *, pin=None, cert=None, token=None, candidate=None,
             publisher_name="publisher-first"):
        return publisher.submit(
            candidate or self.candidate, self.binary, publisher_name,
            token or self.token_file, self.origin, cert or self.cert,
            pin if pin is not None else self.pin)

    def test_real_https_ca_hostname_leaf_pin_and_exact_quarantine_bytes(self):
        result = self.send()
        self.assertEqual(result["status"], "quarantined")
        self.assertTrue(result["local_token_authenticated"])
        self.assertFalse(result["publisher_identity_independently_verified"])
        self.assertFalse(result["owner_review_approved"])
        self.assertFalse(result["public_distribution_authorized"])
        folder, receipt = inbox.load(self.root, result["submission_id"])
        self.assertEqual((folder / "candidate.exe").read_bytes(), self.body)
        self.assertEqual(receipt["claimed_publisher"], "publisher-first")
        self.assertEqual(inbox.verify_events(folder)[0], "quarantined")
        self.assertEqual(list(self.incoming.iterdir()), [])
        self.assertEqual((folder / "submission.json").stat().st_mode & 0o077, 0)

    def test_real_tls_running_server_honors_token_rotation_and_revocation(self):
        first = self.send()
        self.assertEqual(first["status"], "quarantined")
        changed = token_admin.change_registry(self.credentials, "rotate", "publisher-first")
        with self.assertRaises(local_submit_error()):
            self.send()
        fresh_file = self.work / "new-token-secret.txt"
        fresh_file.write_text(changed["one_time_secret"] + "\n", encoding="ascii")
        fresh_file.chmod(0o600)
        # The same TLS service instance must immediately use the new token.
        second = self.send(token=fresh_file)
        self.assertEqual(second["status"], "quarantined")
        self.assertEqual(len(list(self.root.iterdir())), 2)
        token_admin.change_registry(self.credentials, "revoke", "publisher-first")
        with self.assertRaises(local_submit_error()):
            self.send(token=fresh_file)
        self.assertEqual(len(list(self.root.iterdir())), 2)

    def test_wrong_tls_fingerprint_fails_before_sending_publisher_token(self):
        self.assertRaises(publisher.RemotePublisherError, self.send, pin="f" * 64)
        self.assertEqual(list(self.root.iterdir()), [])
        self.assertEqual(list(self.incoming.iterdir()), [])

    def test_missing_or_wrong_root_ca_does_not_post_bytes(self):
        missing = self.work / "missing-ca.pem"
        with self.assertRaises((OSError, ValueError, ssl.SSLError)):
            self.send(cert=missing)
        with self.assertRaises((ssl.SSLError, OSError)):
            self.send(cert=self.key)
        self.assertEqual(list(self.root.iterdir()), [])

    def test_http_plaintext_rejected_by_tls_only_server(self):
        raw = socket.create_connection(("127.0.0.1", self.server.server_port), timeout=5)
        try:
            raw.settimeout(5)
            raw.sendall(b"GET /v1/submissions HTTP/1.1\r\nHost: localhost\r\n\r\n")
            try:
                response = raw.recv(200)
                self.assertNotIn(b"HTTP/1.1 200", response)
                self.assertNotIn(b"HTTP/1.0 202", response)
            except (ConnectionResetError, ssl.SSLError, OSError):
                pass
        finally:
            raw.close()
        self.assertEqual(list(self.root.iterdir()), [])

    def test_wrong_token_and_tenant_identity_rejected_without_private_copy(self):
        bad_token = self.work / "bad-secret.txt"
        bad_token.write_text("Z" * 80, encoding="ascii")
        bad_token.chmod(0o600)
        with self.assertRaises(local_submit_error()):
            self.send(token=bad_token)
        # The local streaming client itself rejects the cross-tenant source
        # claim before sending a single byte over the authenticated channel.
        with self.assertRaises(inbox.QuarantineError):
            self.send(publisher_name="publisher-second")
        self.assertEqual(list(self.root.iterdir()), [])

    def test_remote_service_does_not_expose_unreviewed_approval_endpoints(self):
        transport = publisher.secure_connection(self.origin, self.cert, self.pin)
        try:
            transport.request("GET", "/v1/approve")
            result = transport.getresponse()
            self.assertEqual(result.status, 405)
            self.assertEqual(json.load(result), {"error": "read_api_disabled"})
        finally:
            transport.close()
        self.assertEqual(list(self.root.iterdir()), [])

    def test_external_binding_is_opt_in_and_tls_key_is_private(self):
        with self.assertRaises(gateway.IntakeServiceError):
            remote.checked_bind("0.0.0.0", allow_public=False)
        with self.assertRaises(gateway.IntakeServiceError):
            remote.checked_bind("192.0.2.9", allow_public=False)
        self.assertEqual(remote.checked_bind("0.0.0.0", allow_public=True),
                         "0.0.0.0")
        self.key.chmod(0o644)
        with self.assertRaises(gateway.IntakeServiceError):
            remote.TLSQuarantineServer(
                self.root, self.incoming, self.credentials, self.cert, self.key)
        self.key.chmod(0o600)

    def test_https_origin_restrictions_and_api_safety(self):
        for bad in (
            "http://localhost:443", "https://user:secret@localhost",
            "https://localhost/approve", "https://localhost/?token=unsafe",
            "https://localhost/#fragment", "https://localhost:99999",
            "https://localhost\\evil"
        ):
            with self.subTest(origin=bad):
                with self.assertRaises(publisher.RemotePublisherError):
                    publisher.checked_origin(bad)
        self.assertEqual(publisher.checked_origin(self.origin),
                         ("localhost", self.server.server_port))


def local_submit_error():
    import local_publisher_submit
    return local_publisher_submit.SubmitError


if __name__ == "__main__":
    unittest.main()
